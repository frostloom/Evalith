#!/usr/bin/env bash
# Start the EE-free workbench from source for a local verification run.
#
# The generated tree must exist first:
#   python3 workbench/build.py --source /path/to/rhesis
#   (cd workbench/.workbench/ee-free/apps/backend && uv sync --extra all --extra cpu \
#       --no-install-package torch --no-dev)
#   (cd workbench/.workbench/ee-free/apps/frontend && npm ci && npm run build)
#
# This script starts PostgreSQL/Redis in Docker, runs migrations, then starts the
# backend and frontend on the host. It never uses a published Rhesis image.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
WORKBENCH="$ROOT/.workbench"
TREE="$WORKBENCH/ee-free"
ENV_FILE="$WORKBENCH/rhesis.env"
LOG_DIR="$WORKBENCH/logs"
PID_DIR="$WORKBENCH/pids"

if [[ ! -d "$TREE/apps/backend" ]]; then
  echo "missing generated tree; run: python3 workbench/build.py --source /path/to/rhesis" >&2
  exit 1
fi
mkdir -p "$LOG_DIR" "$PID_DIR"

if [[ ! -f "$ENV_FILE" ]]; then
  python3 - "$ENV_FILE" <<'PY'
import base64
import secrets
import sys
from pathlib import Path

path = Path(sys.argv[1])
values = {
    "DB_ENCRYPTION_KEY": base64.urlsafe_b64encode(secrets.token_bytes(32)).decode(),
    "JWT_SECRET_KEY": secrets.token_hex(32),
    "SESSION_SECRET_KEY": secrets.token_hex(32),
    "NEXTAUTH_SECRET": secrets.token_hex(32),
}
lines = [
    "# Generated by workbench/run_local.sh. Local disposable stack only.",
    *[f"{key}={value}" for key, value in values.items()],
    "BACKEND_ENV=local",
    "FRONTEND_ENV=local",
    "QUICK_START=true",
    "DB_HOST=127.0.0.1",
    "DB_PORT=55432",
    "DB_NAME=rhesis-db",
    "APP_DB_USER=rhesis-user",
    "APP_DB_PASS=rhesis-password",
    "ADMIN_DB_USER=rhesis-user",
    "ADMIN_DB_PASS=rhesis-password",
    "BROKER_URL=redis://:rhesis-redis-pass@127.0.0.1:56379/0",
    "CELERY_RESULT_BACKEND=redis://:rhesis-redis-pass@127.0.0.1:56379/1",
    "API_BASE_URL=http://127.0.0.1:8080",
    "BACKEND_URL=http://127.0.0.1:8080",
    "FRONTEND_URL=http://127.0.0.1:3000",
    "NEXTAUTH_URL=http://127.0.0.1:3000",
    "RHESIS_SKIP_GARAK_WARM_CACHE=true",
    "BRAND_PRODUCT_NAME=Evalith",
    "BRAND_FAVICON_URL=/evalith-mark.svg",
    "BRAND_PRIMARY_COLOR=#164B40",
    "BRAND_SECONDARY_COLOR=#8A5A11",
    "OTEL_RHESIS_TELEMETRY_ENABLED=false",
    "OTEL_SDK_DISABLED=true",
    "ENABLE_RHESIS_KEY=false",
    "RHESIS_CONNECTOR_DISABLED=true",
    "STORAGE_SERVICE_URI=file:///tmp/evalith-workbench-storage",
    "LOG_LEVEL=INFO",
]
path.write_text("\n".join(lines) + "\n", encoding="utf-8")
PY
  chmod 600 "$ENV_FILE"
fi

set -a
# shellcheck disable=SC1090
source "$ENV_FILE"
set +a

echo "[workbench] starting postgres/redis"
docker compose -f "$ROOT/compose.deps.yaml" up -d
for _ in $(seq 1 60); do
  if docker exec evalith-workbench-postgres pg_isready -U rhesis-user -d rhesis-db >/dev/null 2>&1; then
    break
  fi
  sleep 1
done
docker exec evalith-workbench-postgres pg_isready -U rhesis-user -d rhesis-db >/dev/null

echo "[workbench] running migrations"
(
  cd "$TREE/apps/backend/src/rhesis/backend"
  uv run alembic upgrade head
) >"$LOG_DIR/migrate.log" 2>&1 || {
  echo "migration failed; see $LOG_DIR/migrate.log" >&2
  tail -40 "$LOG_DIR/migrate.log" >&2
  exit 1
}

if [[ -f "$PID_DIR/backend.pid" ]] && kill -0 "$(cat "$PID_DIR/backend.pid")" 2>/dev/null; then
  echo "[workbench] backend already running"
else
  echo "[workbench] starting backend on 127.0.0.1:8080"
  (
    cd "$TREE/apps/backend"
    nohup uv run uvicorn rhesis.backend.app.main:app \
      --host 127.0.0.1 --port 8080 >"$LOG_DIR/backend.log" 2>&1 &
    echo $! >"$PID_DIR/backend.pid"
  )
fi

if [[ -f "$PID_DIR/frontend.pid" ]] && kill -0 "$(cat "$PID_DIR/frontend.pid")" 2>/dev/null; then
  echo "[workbench] frontend already running"
else
  echo "[workbench] starting frontend on 127.0.0.1:3000"
  (
    cd "$TREE/apps/frontend"
    NEXT_TELEMETRY_DISABLED=1 PORT=3000 nohup npm start -- --hostname 127.0.0.1 >"$LOG_DIR/frontend.log" 2>&1 &
    echo $! >"$PID_DIR/frontend.pid"
  )
fi

if [[ -f "$PID_DIR/worker.pid" ]] && kill -0 "$(cat "$PID_DIR/worker.pid")" 2>/dev/null; then
  echo "[workbench] worker already running"
else
  echo "[workbench] starting architect worker"
  (
    cd "$TREE/apps/backend"
    nohup uv run celery -A rhesis.backend.celery.core:app worker       -Q architect --pool=solo --loglevel=INFO       >"$LOG_DIR/worker.log" 2>&1 &
    echo $! >"$PID_DIR/worker.pid"
  )
fi

for _ in $(seq 1 90); do
  if curl -fsS http://127.0.0.1:8080/health >/dev/null 2>&1; then
    break
  fi
  sleep 1
done
curl -fsS http://127.0.0.1:8080/health
echo
for _ in $(seq 1 90); do
  if curl -fsS http://127.0.0.1:3000/api/health >/dev/null 2>&1; then
    break
  fi
  sleep 1
done
if ! curl -fsS http://127.0.0.1:3000/api/health >/dev/null 2>&1; then
  echo "[workbench] frontend did not become healthy; see $LOG_DIR/frontend.log" >&2
  exit 1
fi
echo "[workbench] backend http://127.0.0.1:8080  frontend http://127.0.0.1:3000"
echo "[workbench] logs: $LOG_DIR"
echo "[workbench] stop: workbench/stop_local.sh"
